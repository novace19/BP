import { test } from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import { createApp } from '../src/server.js';
import { hashPassword } from '../src/security.js';
import { populate, NOW } from './fixtures.js';

test('HTTP autentizace, CSRF, oprávnění, rezervace a soukromí',async t=>{
  const app=await createApp({dbPath:':memory:',clock:()=>NOW});populate(app.db,await hashPassword('TestovaciHeslo123!'));
  app.server.listen(0,'127.0.0.1');await once(app.server,'listening');
  const base=`http://127.0.0.1:${app.server.address().port}`;
  t.after(async()=>{app.server.closeAllConnections();await new Promise(r=>app.server.close(r));app.db.close();});
  function client(){let cookie='',csrf='';return async(path,method='GET',body,extra={})=>{
    const r=await fetch(base+path,{method,headers:{cookie,...(method==='GET'?{}:{'Content-Type':'application/json','X-CSRF-Token':csrf}),...extra},body:body===undefined?undefined:JSON.stringify(body)});
    if(r.headers.get('set-cookie'))cookie=r.headers.get('set-cookie').split(';')[0];
    const result=await r.json();if(result.csrf)csrf=result.csrf;return {status:r.status,data:result,headers:r.headers};
  };}
  const one=client(),two=client(),anon=client();
  assert.equal((await anon('/api/me')).data.user,null);
  assert.equal((await anon('/api/admin/users')).status,401);
  assert.equal((await anon('/api/auth/login','POST',{email:'one@test.cz',password:'TestovaciHeslo123!'},{'X-CSRF-Token':'bad'})).status,403);
  assert.equal((await one('/api/me')).status,200);await two('/api/me');
  const login=await one('/api/auth/login','POST',{email:'one@test.cz',password:'TestovaciHeslo123!'});
  assert.equal(login.status,200);assert.equal(login.data.user.role,'client');assert.match(login.headers.get('set-cookie'),/HttpOnly/);
  assert.equal((await two('/api/auth/login','POST',{email:'two@test.cz',password:'TestovaciHeslo123!'})).status,200);
  assert.equal((await one('/api/admin/users')).status,403);
  assert.equal((await one('/api/reservations','POST',{session_id:1},{Origin:'https://evil.test'})).status,403);
  const booking=await one('/api/reservations','POST',{session_id:1});assert.equal(booking.status,201);
  assert.equal((await two(`/api/reservations/${booking.data.id}/cancel`,'POST',{})).status,404);
  assert.deepEqual((await two('/api/reservations')).data,[]);
  const listed=await one('/api/reservations');assert.equal(listed.data.length,1);assert.ok(!JSON.stringify(listed.data).includes('password'));
  assert.equal((await one(`/api/reservations/${booking.data.id}/cancel`,'POST',{})).status,200);
  assert.equal((await one('/api/profile/password','POST',{current_password:'wrong',password:'NoveTestovaciHeslo123'})).status,400);
  assert.equal((await one('/api/profile/password','POST',{current_password:'TestovaciHeslo123!',password:'NoveTestovaciHeslo123'})).status,200);
  await one('/api/auth/logout','POST',{});assert.equal((await one('/api/reservations')).status,401);
  assert.equal((await one('/api/auth/login','POST',{email:'one@test.cz',password:'TestovaciHeslo123!'})).status,401);
  assert.equal((await one('/api/auth/login','POST',{email:'one@test.cz',password:'NoveTestovaciHeslo123'})).status,200);
  const registration=await anon('/api/auth/register','POST',{name:'Nový klient',email:' new@test.cz ',password:'RegistracniHeslo123',role:'admin'});
  assert.equal(registration.status,201);assert.equal(registration.data.user.role,'client');
  assert.equal((await anon('/api/auth/register','POST',{name:'Duplicitní',email:'NEW@test.cz',password:'RegistracniHeslo123'})).status,409);
  const admin=client();await admin('/api/me');
  assert.equal((await admin('/api/auth/login','POST',{email:'admin@test.cz',password:'TestovaciHeslo123!'})).status,200);
  const trainer=await admin('/api/admin/trainers','POST',{name:'Nový trenér',bio:'Profil',specialty:'Síla'});assert.equal(trainer.status,201);
  const room=await admin('/api/admin/rooms','POST',{name:'Tréninková zóna',capacity:2});assert.equal(room.status,201);
  const lesson=await admin('/api/admin/lessons','POST',{name:'Osobní vedení',description:'Trénink',kind:'personal',duration:60,color:'blue'});assert.equal(lesson.status,201);
  const sessionData={lesson_id:lesson.data.id,trainer_id:trainer.data.id,room_id:room.data.id,start_at:NOW+86400000,end_at:NOW+90000000,capacity:1,status:'published'};
  const session=await admin('/api/admin/sessions','POST',sessionData);assert.equal(session.status,201);
  const adminBooking=await admin('/api/reservations','POST',{session_id:session.data.id,user_id:registration.data.user.id});assert.equal(adminBooking.status,201);
  assert.equal((await anon('/api/reservations')).data[0].id,adminBooking.data.id);
  assert.equal((await admin(`/api/admin/sessions/${session.data.id}`,'PUT',{...sessionData,status:'cancelled'})).status,200);
  assert.equal((await anon('/api/reservations')).data[0].status,'cancelled');
  const visit=await admin('/api/admin/visits','POST',{user_id:registration.data.user.id,note:'Vstup do posilovny'});assert.equal(visit.status,201);
  assert.equal((await anon('/api/visits')).data.length,1);
  assert.ok((await admin('/api/admin/audit')).data.length>=6);
  assert.equal((await admin(`/api/admin/users/${registration.data.user.id}`,'PUT',{name:'Nový klient',role:'client',active:0})).status,200);
  assert.equal((await anon('/api/reservations')).status,401);
  const root=await fetch(base);assert.equal(root.status,200);assert.match(root.headers.get('content-security-policy'),/script-src 'self'/);assert.match(await root.text(),/lang="cs"/);
  assert.equal((await fetch(base+'/src/db.js')).status,404);
});
