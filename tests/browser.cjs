const { chromium } = require('playwright');
const fs = require('fs');
(async () => {
  fs.mkdirSync('tests/.runtime', { recursive: true });
  const browser = await chromium.launch({headless: true, ...(process.env.FITNESS_CHROME ? {executablePath:process.env.FITNESS_CHROME} : {})});
  const page = await browser.newPage({viewport:{width:1440,height:1100}});
  const errors = [];
  page.on('pageerror', e => errors.push(String(e)));
  await page.goto('http://127.0.0.1:8080/');
  await page.screenshot({path:'tests/.runtime/home-desktop.png',fullPage:true});
  await page.goto('http://127.0.0.1:8080/index.php?page=login');
  await page.getByLabel('E-mail',{exact:true}).fill('admin@example.test');
  await page.getByLabel('Heslo',{exact:true}).fill('Admin-test-1234');
  await Promise.all([page.waitForURL('**page=schedule'),page.getByRole('button',{name:'Přihlásit se',exact:true}).click()]);
  await page.goto('http://127.0.0.1:8080/index.php?page=admin');
  await page.screenshot({path:'tests/.runtime/admin-desktop.png',fullPage:true});
  await page.getByRole('link',{name:'Termíny',exact:true}).click();
  await page.getByLabel('Lekce').selectOption('1');
  await page.getByLabel('Trenér').selectOption('1');
  await page.getByLabel('Sál').selectOption('1');
  const future = new Date(Date.now()+40*86400000).toISOString().slice(0,10)+'T10:00';
  await page.getByLabel('Začátek',{exact:true}).fill(future);
  await page.getByLabel('Kapacita',{exact:true}).fill('10');
  await Promise.all([page.waitForURL('**page=admin-sessions'),page.getByRole('button',{name:'Zveřejnit termín'}).click()]);
  if(!await page.getByRole('status').filter({hasText:'Termín je zveřejněný'}).count()) throw new Error('Termín nevytvořen');
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://127.0.0.1:8080/index.php?page=schedule');
  if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)) throw new Error('Mobilní rozvrh přetéká');
  await page.screenshot({path:'tests/.runtime/schedule-mobile.png',fullPage:true});
  await page.goto('http://127.0.0.1:8080/index.php?page=profile');
  if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)) throw new Error('Mobilní profil přetéká');
  if(errors.length) throw new Error(errors.join('\n'));
  await browser.close();
  console.log('Browser: login, admin schedule creation and mobile layout passed');
})().catch(e=>{console.error(e);process.exit(1)});
